/**
 * The generated half of docs/guide/reference, and the checks that keep the rest honest.
 *
 *   npm run docs:gen     write mcp-tools.md and http-api.md from the running code
 *   npm run docs:check   exit 1 when either is stale, a doc link is broken, an image is orphaned,
 *                        or an environment variable is read but not documented (or the reverse)
 *
 * tests/unit/docs/reference.test.ts runs the same checks, so `npm test` fails on drift.
 * Nothing here opens a database or a socket: tools and routes are listed, never called.
 */
