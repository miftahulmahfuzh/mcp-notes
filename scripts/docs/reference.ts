const NOTES_GROUP = { title: 'Notes', guide: '../claude-code.md' };

/** Every tool the MCP server registers, in registration order. Lists them; calls none. */
export async function listMcpTools(): Promise<ToolDoc[]> {
  const server = createMcpServer({} as ToolDeps);
  const [serverSide, clientSide] = InMemoryTransport.createLinkedPair();
  await server.connect(serverSide);
  const client = new Client({ name: 'docs-reference', version: '1' });
  await client.connect(clientSide);
  try {
    const { tools } = await client.listTools();
    return tools.map((t) => ({
      name: t.name,
      title: t.title ?? t.name,
      description: (t.description ?? '').trim(),
      readOnly: t.annotations?.readOnlyHint === true,
      schema: t.inputSchema as JsonSchema,
    }));
  } finally {
    await client.close();
    await server.close();
  }
}

function typeOf(schema: JsonSchema): string {
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' \\| ');
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' \\| ');
  if (schema.type === 'array') return `${schema.items ? typeOf(schema.items) : 'any'}[]`;
  if (Array.isArray(schema.type)) return schema.type.join(' \\| ');
  return schema.type ?? 'any';
}

/** One table cell: no newlines, no bare pipes. */
function cell(text: string): string {
  return text.replace(/\s*\n\s*/g, ' ').replace(/(?<!\\)\|/g, '\\|').trim();
}

function argumentRows(schema: JsonSchema, prefix = ''): string[] {
  const required = new Set(schema.required ?? []);
  const rows: string[] = [];
  for (const [name, prop] of Object.entries(schema.properties ?? {})) {
    const full = prefix + name;
    rows.push(
      `| \`${full}\` | ${typeOf(prop)} | ${required.has(name) ? 'yes' : ''} | ${cell(prop.description ?? '')} |`,
    );
    // One level down is enough to name what an object argument holds (e.g. `origin.repo`).
    if (prefix === '' && prop.type === 'object') rows.push(...argumentRows(prop, `${full}.`));
  }
  return rows;
}

export function renderMcpTools(tools: ToolDoc[]): string {
  const groups = [...TOOL_GROUPS.map((g) => ({ ...g, tools: [] as ToolDoc[] })), { ...NOTES_GROUP, tools: [] as ToolDoc[] }];
  const notes = groups[groups.length - 1]!;
  for (const tool of tools) (groups.find((g) => 'match' in g && g.match(tool.name)) ?? notes).tools.push(tool);
  // Notes first: they are the tools every `/n` request starts from.
  const ordered = [notes, ...groups.slice(0, -1)].filter((g) => g.tools.length > 0);

  const out: string[] = [
    '# MCP tools',
    '',
    GENERATED,
    '',
    `The ${tools.length} tools the \`notes\` MCP server at \`/mcp\` registers, with the descriptions and arguments`,
    'Claude sees. "Read-only" is the tool\'s own `readOnlyHint`.',
    '',
  ];
  for (const group of ordered) {
    out.push(`- [${group.title}](#${group.title.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')}) (${group.tools.length}): ${group.tools.map((t) => `\`${t.name}\``).join(', ')}`);
  }
  for (const group of ordered) {
    out.push('', `## ${group.title}`, '', `Guide: [${path.basename(group.guide)}](${group.guide})`);
    for (const tool of group.tools) {
      out.push('', `### \`${tool.name}\``, '', `**${tool.title}**${tool.readOnly ? ' · read-only' : ''}`, '', tool.description);
      const rows = argumentRows(tool.schema);
      if (rows.length > 0) out.push('', '| Argument | Type | Required | Meaning |', '| --- | --- | --- | --- |', ...rows);
      else out.push('', 'No arguments.');
    }
  }
  return `${out.join('\n')}\n`;
}

// HTTP routes

/** Every route the daemon serves as `METHOD /path`, deduplicated, without the SPA fallback. */
export function listHttpRoutes(): string[] {
  const config = loadConfig({ env: { DATABASE_URL: 'postgres://docs@127.0.0.1:1/docs' }, envFile: false });
  // Route tables are built from the routers alone; no handler runs, so the services stay empty.
  const deps = { config, db: {}, events: {}, service: {}, embedder: null, imageEmbedder: null, chat: {}, adversary: null, movies: null };
  const app = createApp(deps as unknown as AppDeps);
  const seen = new Set<string>();
  for (const route of app.routes) {
    if (route.method === 'ALL' || route.path === '/*') continue;
    // Hono keeps a param's pattern in the path (`:id{[a-z]+-[0-9]+}`); the reference names the param only.
    seen.add(`${route.method} ${route.path.replace(/\{[^}]*\}+/g, '')}`);
  }
  return [...seen];
}

export function httpRouteProblems(routes: string[]): string[] {
  const documented = new Map<string, number>();
  for (const group of HTTP_GROUPS) for (const key of Object.keys(group.routes)) documented.set(key, (documented.get(key) ?? 0) + 1);
  const problems: string[] = [];
  for (const route of routes) if (!documented.has(route)) problems.push(`route ${route} has no entry in scripts/docs/httpRoutes.ts`);
  for (const [key, count] of documented) {
    if (!routes.includes(key)) problems.push(`scripts/docs/httpRoutes.ts describes ${key}, which the daemon does not serve`);
    if (count > 1) problems.push(`scripts/docs/httpRoutes.ts describes ${key} ${count} times`);
  }
  return problems;
}

export function renderHttpApi(): string {
  const out: string[] = [
    '# HTTP API',
    '',
    GENERATED,
    '',
    'Every route `notesd` serves on `127.0.0.1:7317`. The list comes from the daemon\'s own route table;',
    'the descriptions live in `scripts/docs/httpRoutes.ts`, and `npm test` fails when a route has none.',
  ];
  for (const group of HTTP_GROUPS) {
    out.push('', `## ${group.title}`, '');
    if (group.intro) out.push(group.intro, '');
    out.push('| Route | What it does |', '| --- | --- |');
    for (const [route, text] of Object.entries(group.routes)) out.push(`| \`${route}\` | ${cell(text)} |`);
  }
  return `${out.join('\n')}\n`;
}

// Environment variables

function walk(dir: string, keep: (file: string) => boolean, out: string[] = []): string[] {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === 'dist') continue;
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full, keep, out);
    else if (keep(full)) out.push(full);
  }
  return out;
}

/**
 * Every environment variable the shipped code reads, found by how the code reads one, never from a
 * list of names. Scanned: src/, claude/, scripts/ and the two root configs that read the
 * environment (drizzle.config.ts, vitest.config.ts). The read patterns:
 *
 * - a property of anything whose name ends in `env`: `env.NAME`, `process.env['NAME']`,
 *   `realEnv.NAME`, `probe.env.NAME`;
 * - a quoted name bound to an identifier that ends in `Env`, `ENV` or `_KEYS`, which is how a
 *   variable read through a constant is named (`EXPLORER_ENV = 'NOTESD_EXPLORER_BIN'`,
 *   `repoDirEnv: 'SEER_DIR'`, `SETTING_KEYS = ['CONNECTOR_TIMEOUT_MS', ...]`);
 * - the quoted names src/config.ts hands its parsers;
 * - in a shell script, a parameter with a default or a set-test (`${NAME:-default}`, `${NAME+x}`:
 *   the script takes it from its caller) and `export NAME=` (the script hands it to what it starts).
 *   A plain `${NAME}` is the script's own variable.
 *
 * A name a new read pattern hides is a gap here: widen the pattern, do not add the name.
 */
export function listEnvVars(): string[] {
  const names = new Set<string>();
  const NAME = '[A-Z][A-Z0-9]*_[A-Z0-9_]+';
  const quoted = new RegExp(`['"](${NAME})['"]`, 'g');
  const sources = [
    ...walk(path.join(REPO_ROOT, 'src'), (f) => f.endsWith('.ts')),
    ...walk(path.join(REPO_ROOT, 'claude'), (f) => /\.(mjs|ts)$/.test(f) && !/\.test\./.test(f)),
    ...walk(path.join(REPO_ROOT, 'scripts'), (f) => /\.(mjs|sh)$/.test(f)),
    path.join(REPO_ROOT, 'drizzle.config.ts'),
    path.join(REPO_ROOT, 'vitest.config.ts'),
  ];
  for (const file of sources) {
    if (!existsSync(file)) continue;
    const text = readFileSync(file, 'utf8');
    for (const m of text.matchAll(/env(?:\.|\[['"])([A-Z][A-Z0-9_]{2,})/gi)) if (m[1] === m[1]!.toUpperCase()) names.add(m[1]!);
    for (const bound of text.matchAll(/\b\w*(?:Env|ENV|_KEYS)\s*[:=]\s*(\[[^\]]*\]|['"][^'"\n]*['"])/g)) {
      for (const m of bound[1]!.matchAll(quoted)) names.add(m[1]!);
    }
    if (file.endsWith('.sh')) for (const m of text.matchAll(new RegExp(`(?:\\$\\{(${NAME})(?::?[-+])|^\\s*export (${NAME})=)`, 'gm'))) names.add((m[1] ?? m[2])!);
  }
  const config = readFileSync(path.join(REPO_ROOT, 'src', 'config.ts'), 'utf8');
  for (const m of config.matchAll(quoted)) names.add(m[1]!);
  return [...names].filter((n) => !(n in ENV_IGNORED)).sort();
}

export function envVarProblems(): string[] {
  if (!existsSync(CONFIGURATION_FILE)) return [`${rel(CONFIGURATION_FILE)} is missing`];
  const text = readFileSync(CONFIGURATION_FILE, 'utf8');
  const documented = new Set<string>();
  // The first cell of a table row names the variable(s) that row documents.
  for (const line of text.split('\n')) {
    const first = /^\|([^|]*)\|/.exec(line)?.[1];
    if (first) for (const m of first.matchAll(/`([A-Z][A-Z0-9_]+)`/g)) documented.add(m[1]!);
  }
  const read = listEnvVars();
  const problems: string[] = [];
  for (const name of read) if (!documented.has(name)) problems.push(`${name} is read by the code but has no row in ${rel(CONFIGURATION_FILE)}`);
  for (const name of documented) if (!read.includes(name)) problems.push(`${rel(CONFIGURATION_FILE)} documents ${name}, which no code reads`);
  return problems;
}

// Links and media

const rel = (file: string): string => path.relative(REPO_ROOT, file);

/** The documents a reader follows: the root README, CLAUDE.md and everything under docs/guide. */
export function docFiles(): string[] {
  return [path.join(REPO_ROOT, 'README.md'), path.join(REPO_ROOT, 'CLAUDE.md'), ...walk(GUIDE_DIR, (f) => f.endsWith('.md'))];
}

/** Broken relative links and images, and pictures under docs/guide/img that no document shows. */
export function linkProblems(): string[] {
  const problems: string[] = [];
  const shown = new Set<string>();
  for (const file of docFiles()) {
    // Fenced code is example text, not links.
    const text = readFileSync(file, 'utf8').replace(/```[\s\S]*?```/g, '');
    const targets = [
      ...[...text.matchAll(/!?\[[^\]]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)].map((m) => m[1]!),
      ...[...text.matchAll(/<(?:img|source|video)[^>]*\ssrc="([^"]+)"/g)].map((m) => m[1]!),
    ];
    for (const target of targets) {
      if (/^(https?:|mailto:|#)/.test(target)) continue;
      const resolved = path.resolve(path.dirname(file), decodeURIComponent(target.split('#')[0]!));
      if (!existsSync(resolved)) problems.push(`${rel(file)} links to ${target}, which does not exist`);
      else shown.add(resolved);
    }
  }
  for (const image of walk(path.join(GUIDE_DIR, 'img'), () => true)) {
    if (!shown.has(image)) problems.push(`${rel(image)} is not shown by any document; delete it or use it`);
  }
  return problems;
}

// Entry point

export interface Generated {
  file: string;
  content: string;
}

export async function generate(): Promise<Generated[]> {
  return [
    { file: MCP_TOOLS_FILE, content: renderMcpTools(await listMcpTools()) },
    { file: HTTP_API_FILE, content: renderHttpApi() },
  ];
}

export async function allProblems(): Promise<string[]> {
  const problems: string[] = [];
  for (const { file, content } of await generate()) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== content) problems.push(`${rel(file)} is stale; run npm run docs:gen`);
  }
  return [...problems, ...httpRouteProblems(listHttpRoutes()), ...envVarProblems(), ...linkProblems()];
}

async function main(): Promise<void> {
  if (process.argv.includes('--check')) {
    const problems = await allProblems();
    for (const p of problems) console.error(`docs: ${p}`);
    console.log(problems.length === 0 ? 'docs: reference is current' : `docs: ${problems.length} problem(s)`);
    process.exit(problems.length === 0 ? 0 : 1);
  }
  for (const { file, content } of await generate()) {
    writeFileSync(file, content);
    console.log(`docs: wrote ${rel(file)}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
